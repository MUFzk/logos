import numpy as np
def E_valiz(x):
    """Bir valiz durumunun enerjisini hesaplar (enerji = -fayda).

    Durum, altı parçanın seçili (1) ya da değil (0) olduğunu gösteren demettir:
    x = (tişört, kazak, bot, sandalet, bere, şapka).

    Fayda değerleri:

    +----------+------------------------------+-------+
    | Tür      | Parça(lar)                   | Fayda |
    +----------+------------------------------+-------+
    | Tek      | tişört (x[0])                |   2   |
    | Tek      | kazak (x[1])                 |   1   |
    | Tek      | bot (x[2])                   |   3   |
    | Tek      | sandalet (x[3])              |   2   |
    | Tek      | bere (x[4])                  |   1   |
    | Tek      | şapka (x[5])                 |   2   |
    | Kış uyum | kazak + bot                  |  +5   |
    | Kış uyum | kazak + bere                 |  +4   |
    | Kış uyum | bot + bere                   |  +5   |
    | Yaz uyum | tişört + sandalet            |  +5   |
    | Yaz uyum | tişört + şapka               |  +5   |
    | Yaz uyum | sandalet + şapka             |  +5   |
    | Çakışma  | her (yaz, kış) çifti (9 çift)|  -3   |
    +----------+------------------------------+-------+

    Enerji faydanın eksi işaretlisidir; fayda ne kadar yüksekse enerji o
    kadar düşüktür. En iyi valiz (yaz: tişört, sandalet, şapka) -21,
    başlangıçtaki kış valizi (kazak, bot, bere) -19 enerjiye sahiptir.

    Args:
        x: 0 ve 1'lerden oluşan, uzunluğu 6 olan demet.

    Returns:
        Durumun enerjisi (düşük = iyi).
    """
    total  = 2 * x[0] + x[1] + 3 * x[2] + 2 * x[3] + x[4] + 2 * x[5]
    total += 5*x[1]*x[2] + 4*x[1]*x[4] + 5*x[2]*x[4]
    total += 5*x[0]*x[3] + 5*x[0]*x[5] + 5*x[3]*x[5]
    total -= 3 * (x[1] + x[2] + x[4]) * (x[0] + x[3] + x[5])
    return -total


def metropolis_adimi(x: tuple, T: float, E) -> tuple:
    """Sıcaklık T'de tek bir Metropolis adımı atar.

    Rastgele seçilen bir parçanın durumu çevrilir (0 ↔ 1). Enerjiyi düşüren
    ya da aynı bırakan hamle her zaman kabul edilir; enerjiyi artıran hamle
    exp(-dE / T) olasılığıyla kabul edilir. Hamle reddedilirse durum değişmez.

    Args:
        x: Mevcut durum; 0 ve 1'lerden oluşan demet (ör. valizdeki parçalar).
        T: Sıcaklık (> 0).
        E: Bir durumu alıp enerjisini döndüren fonksiyon. Düşük enerji = iyi.

    Returns:
        Adım sonundaki durum (yeni durum ya da değişmemiş x).
    """
    # rastgele bir parça seç ve durumunu çevir
    i = np.random.randint(len(x))
    y = x[:i] + (1 - x[i],) + x[i+1:]

    # enerji farkı
    dE = E(y) - E(x)
    if dE <= 0:
        return y

    # kabul kararı
    kabul = np.exp(-dE / T)
    if np.random.random() < kabul:
        return y
    return x


def tavlama(x0: tuple, E, T0: float, T_son: float, alfa: float, ic_adim: int):
    """Benzetimli tavlama (simulated annealing) çalıştırır.

    Sıcaklık T0'dan başlar ve her turun sonunda alfa ile çarpılarak düşer
    (üstel soğutma). Her turda sıcaklık sabit tutulur ve ic_adim kadar
    Metropolis adımı atılır. Tur sayısı ceil(ln(T_son / T0) / ln(alfa)) + 1
    olarak hesaplanır; bu yüzden son turun sıcaklığı T_son'un biraz altında kalır.
    Toplam adım sayısı tur_sayisi * ic_adim'dir.

    Args:
        x0: Başlangıç durumu; 0 ve 1'lerden oluşan demet.
        E: Bir durumu alıp enerjisini döndüren fonksiyon. Düşük enerji = iyi.
        T0: Başlangıç sıcaklığı (> T_son).
        T_son: Hedef son sıcaklık (> 0).
        alfa: Soğutma oranı, 0 < alfa < 1. Küçük alfa = hızlı soğutma.
        ic_adim: Her sıcaklıkta atılan Metropolis adımı sayısı.

    Returns:
        x: Tavlama sonundaki durum.
        T_gecmisi: Her turda kullanılan sıcaklık değerleri.
        E_gecmisi: Her turun sonundaki durumun enerjisi.
    """
    tur_sayisi = max(2, int(np.ceil(np.log(T_son / T0) / np.log(alfa))))

    x = x0
    T = T0
    T_gecmisi = []
    E_gecmisi = []

    for _ in range(tur_sayisi):
        for _ in range(ic_adim):
            #TODO x durumunu T sıcaklığında metropolis_adimi ile güncelleyin.
            x = metropolis_adimi(x, T, E)
        T_gecmisi.append(T)
        E_gecmisi.append(E(x))

        #TODO sıcaklığı alfa ile çarparak düşürün.
        T *= alfa

    return x, T_gecmisi, E_gecmisi